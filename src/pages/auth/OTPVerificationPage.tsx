import React, { useState, useEffect } from 'react';
import { useNavigate, useSearchParams, Link } from 'react-router-dom';
import {
  ShieldCheck,
  Mail,
  CheckCircle2,
  Clock,
  AlertCircle,
  RotateCw,
  Sparkles,
  ArrowLeft,
  ArrowRight,
  Info,
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import { useNotification } from '../../context/NotificationContext';
import { Button } from '../../components/common/Button';
import { MOCK_OTP_CODE } from '../../services/authService';
import {
  clearVerificationTicket,
  readVerificationTicket,
} from '../../utils/verificationTicket';

/** Whether the localStorage auth mock is active. */
const USE_MOCK_AUTH = import.meta.env.VITE_USE_MOCK_AUTH === 'true';
import type { AccountState } from '../../types';

/**
 * Email verification after registration.
 *
 * ===========================================================================
 * EMAIL ONLY. The mobile card and the "verify both" action are gone.
 *
 * BR-001 asked for dual email + mobile OTP, but BR-014 disables SMS, and
 * email-only was confirmed as the approved scope. No SMS provider exists, so
 * a mobile card here could only ever have been theatre.
 *
 * ALSO GONE: the pre-filled "123456" inputs, the "Demo code: 123456" helper
 * banner, the fallback student id, and the `?studentId=` query parameter -
 * the account is now identified by an opaque verification ticket held in
 * sessionStorage, so no internal id reaches the URL. The codes are now real, generated by
 * the backend and sent over the configured delivery adapter - in local
 * development that adapter writes the code to the BACKEND LOG rather than
 * emailing it, so read it from the terminal running `npm run dev:integration`.
 * ===========================================================================
 *
 * VERIFYING IS NOT SIGNING IN. The endpoint returns the account's status and
 * no token, so this page sends the student to the sign-in screen afterwards
 * rather than to a dashboard. The previous version navigated straight to
 * `/student/dashboard` because its mock had called `setUser()` with a full
 * profile - that made a six-digit code equivalent to a password.
 */
export const OTPVerificationPage: React.FC = () => {
  const [searchParams] = useSearchParams();
  const emailParam = searchParams.get('email');

  /**
   * The verification ticket, read ONCE from sessionStorage.
   *
   * Replaces the `studentId` this page used to take from the query string.
   * Read via `useState` initialiser rather than on every render so that
   * clearing it after a successful verification does not immediately flip
   * the page into its "link incomplete" state.
   */
  const [ticket] = useState<string | null>(() => readVerificationTicket());

  const { verifyEmailOtp, resendEmailOtp } = useAuth();
  const { showToast } = useNotification();
  const navigate = useNavigate();

  const [otp, setOtp] = useState('');
  const [isVerifying, setIsVerifying] = useState(false);
  const [isResending, setIsResending] = useState(false);

  const [verified, setVerified] = useState(false);
  const [accountState, setAccountState] = useState<AccountState | undefined>(undefined);
  const [awaitingApproval, setAwaitingApproval] = useState(false);

  const [error, setError] = useState<string | null>(null);

  /**
   * Seconds until a resend is allowed.
   *
   * Starts at 60 because registration has just sent a code and the backend
   * enforces a 60-second cooldown. After a resend the value is taken from the
   * server's own `resendAvailableAt` rather than assumed, so the UI and the
   * server cannot drift apart.
   */
  const [cooldown, setCooldown] = useState(60);

  useEffect(() => {
    if (cooldown <= 0) return;

    const timer = setInterval(() => {
      setCooldown((prev) => (prev > 0 ? prev - 1 : 0));
    }, 1000);

    return () => clearInterval(timer);
  }, [cooldown]);

  /** Turns the server's absolute instant into a countdown. */
  const cooldownFrom = (resendAvailableAt: string): number => {
    const seconds = Math.ceil((new Date(resendAvailableAt).getTime() - Date.now()) / 1000);

    return Number.isFinite(seconds) && seconds > 0 ? seconds : 0;
  };

  const handleVerify = async () => {
    if (ticket === null) return;

    setError(null);
    setIsVerifying(true);
    const res = await verifyEmailOtp(ticket, otp);
    setIsVerifying(false);

    if (!res.success) {
      // The backend's message already carries the useful detail - how many
      // attempts remain, or that a new code is needed - so it is shown as
      // written rather than replaced with a generic string.
      setError(res.error ?? 'That code could not be verified.');
      return;
    }

    setVerified(true);
    setAccountState(res.status?.accountState);
    setAwaitingApproval(res.status?.awaitingAdminApproval ?? false);

    // Spent: a consumed ticket must not linger for the rest of the tab.
    clearVerificationTicket();

    showToast({
      type: 'success',
      title: 'Email Verified',
      message: res.status?.awaitingAdminApproval
        ? 'Your registration is now awaiting admin approval (BR-002).'
        : 'Your email address has been verified.',
    });
  };

  const handleResend = async () => {
    if (ticket === null) return;

    setError(null);
    setIsResending(true);
    const res = await resendEmailOtp(ticket);
    setIsResending(false);

    if (!res.success) {
      setError(res.error ?? 'The code could not be resent.');
      return;
    }

    setOtp('');
    setCooldown(res.status ? cooldownFrom(res.status.resendAvailableAt) : 60);

    showToast({
      type: 'info',
      title: 'Code Sent',
      message: `A new 6-digit code has been sent to ${res.status?.sentTo ?? 'your email address'}.`,
    });
  };

  // No ticket: there is nothing to verify against. Reached when the tab was
  // opened directly, when the ticket has been cleared, or when sessionStorage
  // is unavailable. Recoverable - signing in again issues a fresh one.
  if (ticket === null) {
    return (
      <div className="w-full max-w-2xl mx-auto space-y-6">
        <div className="bg-white p-6 sm:p-8 rounded-2xl border border-slate-200/90 shadow-xl space-y-4 text-center">
          <div className="h-12 w-12 rounded-xl bg-rose-50 text-rose-600 flex items-center justify-center mx-auto">
            <AlertCircle className="h-6 w-6" />
          </div>
          <h1 className="text-xl font-bold text-slate-900">Verification session not found</h1>
          <p className="text-xs text-slate-500 leading-relaxed max-w-sm mx-auto">
            This page needs the verification session created when you submit the registration form
            or sign in. It lasts 15 minutes and is specific to this browser tab. Sign in again to
            start a new one, or register if you do not have an account yet.
          </p>
          <div className="flex items-center justify-center gap-2 pt-1">
            <Link to="/register">
              <Button size="sm" className="py-1.5 text-xs font-semibold">
                Go to Registration
              </Button>
            </Link>
            <Link to="/login">
              <Button size="sm" variant="outline" className="py-1.5 text-xs font-semibold">
                Sign In
              </Button>
            </Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="w-full max-w-2xl mx-auto space-y-6">
      {/* Top Breadcrumb / Return */}
      <div className="flex items-center justify-between">
        <Link
          to="/login"
          className="inline-flex items-center gap-1.5 text-xs font-semibold text-slate-500 hover:text-indigo-600 transition-colors"
        >
          <ArrowLeft className="h-3.5 w-3.5" />
          <span>Back to Sign In</span>
        </Link>
        <span className="text-[11px] font-mono text-slate-400 bg-slate-100 px-2 py-0.5 rounded">
          Rule: BR-001 Email OTP
        </span>
      </div>

      <div className="bg-white p-6 sm:p-8 rounded-2xl border border-slate-200/90 shadow-xl space-y-6">
        {/* Header */}
        <div className="text-center space-y-2">
          <div className="h-12 w-12 rounded-xl bg-indigo-50 text-indigo-600 flex items-center justify-center mx-auto shadow-sm">
            <ShieldCheck className="h-6 w-6" />
          </div>
          <h1 className="text-2xl font-bold text-slate-900 tracking-tight">
            Verify Your Email Address
          </h1>
          <p className="text-xs text-slate-500 max-w-md mx-auto leading-relaxed">
            Enter the 6-digit code we sent to your email address. Once verified, your registration
            goes to the admissions team for approval (<strong>BR-002</strong>).
          </p>
        </div>

        {/* Error Notice */}
        {error && (
          <div className="p-3.5 bg-rose-50 border border-rose-200 text-rose-700 text-xs rounded-xl flex items-start gap-2.5">
            <AlertCircle className="h-4 w-4 shrink-0 mt-0.5" />
            <span>{error}</span>
          </div>
        )}

        {/* Success Banner */}
        {verified && (
          <div className="p-4 bg-emerald-50 border border-emerald-200 rounded-xl flex items-center gap-3">
            <div className="h-9 w-9 rounded-full bg-emerald-500 text-white flex items-center justify-center shrink-0">
              <Sparkles className="h-5 w-5" />
            </div>
            <div className="text-xs">
              <p className="font-bold text-emerald-900">Email Verified</p>
              <p className="text-emerald-700 mt-0.5">
                {awaitingApproval ? (
                  <>
                    Status is now <strong>Pending Admin Approval (BR-002)</strong>. You will be able
                    to sign in once an administrator approves your registration.
                  </>
                ) : (
                  <>
                    Your email address is confirmed
                    {accountState === undefined ? '' : <> (status: <strong>{accountState}</strong>)</>}.
                  </>
                )}
              </p>
            </div>
          </div>
        )}

        {/* Email verification card */}
        <div
          className={`p-4 rounded-xl border transition-all ${
            verified
              ? 'bg-emerald-50/50 border-emerald-200 shadow-sm'
              : 'bg-slate-50/70 border-slate-200 hover:border-slate-300'
          }`}
        >
          <div className="flex items-center justify-between mb-3">
            <div className="flex items-center gap-2">
              <div
                className={`p-1.5 rounded-lg ${
                  verified ? 'bg-emerald-100 text-emerald-700' : 'bg-indigo-100 text-indigo-700'
                }`}
              >
                <Mail className="h-4 w-4" />
              </div>
              <div>
                <h2 className="text-xs font-bold text-slate-900">Email Verification</h2>
                <p
                  className="text-[11px] text-slate-500 truncate max-w-[200px]"
                  title={emailParam ?? undefined}
                >
                  {emailParam ?? 'the address you registered with'}
                </p>
              </div>
            </div>

            {verified ? (
              <span className="inline-flex items-center gap-1 text-[10px] font-semibold text-emerald-700 bg-emerald-100 px-2 py-0.5 rounded-full">
                <CheckCircle2 className="h-3 w-3" />
                Verified
              </span>
            ) : (
              <span className="inline-flex items-center gap-1 text-[10px] font-semibold text-amber-700 bg-amber-100 px-2 py-0.5 rounded-full">
                <Clock className="h-3 w-3" />
                Pending
              </span>
            )}
          </div>

          <div className="space-y-3">
            <div>
              <label htmlFor="email-otp" className="block text-[11px] font-semibold text-slate-700 mb-1">
                6-Digit Email Code
              </label>
              <input
                id="email-otp"
                type="text"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                disabled={verified}
                value={otp}
                onChange={(e) => setOtp(e.target.value.replace(/\D/g, ''))}
                placeholder="------"
                className={`w-full text-center font-mono tracking-widest text-base font-bold py-2 border rounded-lg focus:outline-none transition-all ${
                  verified
                    ? 'bg-emerald-100/40 text-emerald-800 border-emerald-200 cursor-not-allowed'
                    : 'bg-white border-slate-300 focus:ring-2 focus:ring-indigo-500 text-slate-900'
                }`}
              />
            </div>

            {!verified && (
              <div className="flex items-center gap-2 pt-1">
                <Button
                  type="button"
                  size="sm"
                  disabled={otp.length !== 6}
                  isLoading={isVerifying}
                  onClick={handleVerify}
                  className="flex-1 py-1.5 text-xs font-semibold"
                >
                  Verify Email
                </Button>

                <button
                  type="button"
                  disabled={cooldown > 0 || isResending}
                  onClick={handleResend}
                  className="px-2.5 py-1.5 text-[11px] font-medium border border-slate-200 rounded-lg text-slate-600 hover:bg-slate-100 disabled:opacity-50 disabled:cursor-not-allowed flex items-center gap-1"
                >
                  <RotateCw
                    className={`h-3 w-3 ${cooldown > 0 ? '' : 'text-indigo-600'} ${
                      isResending ? 'animate-spin' : ''
                    }`}
                  />
                  {cooldown > 0 ? `${cooldown}s` : 'Resend'}
                </button>
              </div>
            )}
          </div>
        </div>

        {/* Mock-mode hint: the demo code, shown ONLY in mock mode */}
        {USE_MOCK_AUTH && !verified && (
          <div className="p-3 bg-amber-50 border border-amber-300 rounded-xl flex items-start gap-2.5">
            <Info className="h-4 w-4 shrink-0 mt-0.5 text-amber-700" />
            <p className="text-[11px] text-amber-900 leading-relaxed">
              <strong>Mock mode.</strong> No email is sent and no real code exists. Use{' '}
              <span className="font-mono font-bold">{MOCK_OTP_CODE}</span>. This notice does not
              appear when the real API is in use - there, the code is generated by the backend and
              written to its log in development.
            </p>
          </div>
        )}

        {/* Why there is no mobile step */}
        {!verified && (
          <div className="p-3 bg-slate-50 border border-slate-200 rounded-xl flex items-start gap-2.5">
            <Info className="h-4 w-4 shrink-0 mt-0.5 text-slate-400" />
            <p className="text-[11px] text-slate-500 leading-relaxed">
              Only email verification is required at present. SMS verification is disabled
              (<strong>BR-014</strong>), so your mobile number is recorded but not verified by code.
            </p>
          </div>
        )}

        {/* Next step */}
        {verified && (
          <Button
            type="button"
            onClick={() => navigate('/login')}
            className="w-full py-2 text-xs font-semibold flex items-center justify-center gap-1.5"
          >
            <span>Continue to Sign In</span>
            <ArrowRight className="h-3.5 w-3.5" />
          </Button>
        )}
      </div>
    </div>
  );
};
