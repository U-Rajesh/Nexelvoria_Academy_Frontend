import React, { useCallback, useEffect, useState } from 'react';
import { Download, FileSpreadsheet, FileText, RefreshCw, Search } from 'lucide-react';
import { useNotification } from '../../context/NotificationContext';
import { Button } from '../common/Button';
import { Card } from '../common/Card';
import {
  reportsService,
  type ExportFormat,
  type ReportColumn,
  type ReportDefinition,
  type ReportFilters,
  type ReportPageResult,
} from '../../services/reportsService';

const inputCls = 'px-3 py-2 border border-slate-200 rounded-lg text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500 bg-white';
const PAGE_SIZE = 25;

/** On-screen rendering that matches the export formatting (money 2 dp, IST timestamps). */
export function displayCell(value: unknown, type: ReportColumn['type']): string {
  if (value === null || value === undefined || value === '') return '—';
  if (type === 'money') {
    const n = Number(value);
    return Number.isFinite(n) ? n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 }) : String(value);
  }
  if (type === 'int') return String(value);
  const d = new Date(String(value));
  if (Number.isNaN(d.getTime())) return String(value);
  if (type === 'date') return d.toISOString().slice(0, 10);
  if (type === 'datetime') return d.toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'medium', timeStyle: 'short' });
  return String(value);
}

interface Props {
  title: string;
  subtitle: string;
}

/**
 * Custom reports (REP-002) with server-side filtering and pagination, and
 * genuine CSV / Excel / PDF exports (REP-003..005) generated by the server
 * from exactly the filters applied on screen. The catalog comes from the
 * server, so each role only sees the reports it may run (REP-007).
 */
export const ReportsWorkspace: React.FC<Props> = ({ title, subtitle }) => {
  const { showToast } = useNotification();
  const [catalog, setCatalog] = useState<ReportDefinition[]>([]);
  const [catalogError, setCatalogError] = useState<string | null>(null);
  const [code, setCode] = useState<string>('');
  const [draft, setDraft] = useState<ReportFilters>({});
  /** Filters actually applied to the visible result (and to exports). */
  const [applied, setApplied] = useState<ReportFilters>({});
  const [statuses, setStatuses] = useState<string[]>([]);
  const [page, setPage] = useState(1);
  const [result, setResult] = useState<ReportPageResult | null>(null);
  const [summaryRows, setSummaryRows] = useState<Record<string, unknown>[] | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [exporting, setExporting] = useState<ExportFormat | null>(null);
  /** Selected fields (custom report); empty means every field. */
  const [fields, setFields] = useState<string[]>([]);

  const def = catalog.find((c) => c.code === code);

  useEffect(() => {
    reportsService.getCatalog().then((res) => {
      if (!res.success) return setCatalogError(res.error || 'Reports could not be loaded.');
      setCatalog(res.data);
      if (res.data[0]) setCode(res.data[0].code);
    });
  }, []);

  useEffect(() => {
    if (!def) return;
    setStatuses([]);
    if (def.hasStatus) reportsService.getStatuses(def.code).then((res) => res.success && setStatuses(res.data));
  }, [def]);

  const load = useCallback(async () => {
    if (!def) return;
    setLoading(true);
    setError(null);
    if (def.code === 'financial-summary') {
      const res = await reportsService.getFinancialSummary({ from: applied.from, to: applied.to });
      setLoading(false);
      if (res.success && res.data) {
        setSummaryRows(res.data.rows);
        setResult(null);
      } else setError(res.error || 'The financial summary could not be generated.');
      return;
    }
    const res = await reportsService.runReport(def.code, applied, page, PAGE_SIZE);
    setLoading(false);
    if (res.success && res.data) {
      setResult(res.data);
      setSummaryRows(null);
    } else setError(res.error || 'The report could not be generated.');
  }, [def, applied, page]);

  useEffect(() => {
    load();
  }, [load]);

  const selectReport = (next: string) => {
    setCode(next);
    setDraft({});
    setApplied({});
    setPage(1);
    setResult(null);
    setSummaryRows(null);
    setFields([]);
  };

  const toggleField = (key: string) => {
    if (!def) return;
    const current = fields.length ? fields : def.columns.map((c) => c.key);
    const next = current.includes(key) ? current.filter((k) => k !== key) : def.columns.map((c) => c.key).filter((k) => k === key || current.includes(k));
    if (next.length === 0) return; // at least one field
    setFields(next.length === def.columns.length ? [] : next);
  };

  const applyFilters = (e: React.FormEvent) => {
    e.preventDefault();
    if (draft.from && draft.to && draft.from > draft.to) {
      setError('The start date must not be after the end date.');
      return;
    }
    setPage(1);
    setApplied({ ...draft, search: draft.search?.trim() || undefined });
  };

  /** The export uses the applied filters and the selected fields, so the file matches the screen. */
  const exportFilters: ReportFilters = { ...applied, ...(fields.length ? { columns: fields.join(',') } : {}) };

  const doExport = async (format: ExportFormat) => {
    if (!def) return;
    setExporting(format);
    const res = await reportsService.exportReport(def.code, format, exportFilters);
    setExporting(null);
    showToast(
      res.success && res.data
        ? { type: 'success', title: 'Report Downloaded', message: `${res.data.fileName} (${res.data.rows} rows).` }
        : { type: 'error', title: 'Export Failed', message: res.error || 'The export could not be generated.' }
    );
  };

  const rows = summaryRows ?? result?.rows ?? [];
  const columns = (def?.columns ?? []).filter((c) => fields.length === 0 || fields.includes(c.key));

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-slate-900 tracking-tight">{title}</h1>
        <p className="text-xs text-slate-500 mt-1">{subtitle}</p>
      </div>

      {catalogError && <Card className="p-4 border border-rose-200 bg-rose-50 text-xs text-rose-800">{catalogError}</Card>}

      <div className="grid grid-cols-1 lg:grid-cols-4 gap-6">
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-400">Report</h3>
          {catalog.map((c) => (
            <button
              key={c.code}
              onClick={() => selectReport(c.code)}
              className={`w-full p-3 rounded-xl border text-left transition-colors ${
                c.code === code ? 'bg-indigo-50 border-indigo-300' : 'bg-white border-slate-200 hover:bg-slate-50'
              }`}
            >
              <h4 className="text-xs font-bold text-slate-900">{c.title}</h4>
              <p className="text-[11px] text-slate-500 mt-0.5">{c.description}</p>
            </button>
          ))}
        </div>

        <div className="lg:col-span-3 space-y-4">
          {def && (
            <Card className="p-4">
              <form onSubmit={applyFilters} className="flex flex-wrap items-end gap-3">
                <div>
                  <label className="block text-[11px] font-semibold text-slate-600 mb-1">{def.dateField} from</label>
                  <input type="date" className={inputCls} value={draft.from ?? ''} onChange={(e) => setDraft({ ...draft, from: e.target.value || undefined })} />
                </div>
                <div>
                  <label className="block text-[11px] font-semibold text-slate-600 mb-1">to</label>
                  <input type="date" className={inputCls} value={draft.to ?? ''} onChange={(e) => setDraft({ ...draft, to: e.target.value || undefined })} />
                </div>
                {def.hasStatus && (
                  <div>
                    <label className="block text-[11px] font-semibold text-slate-600 mb-1">Status</label>
                    <select className={inputCls} value={draft.status ?? ''} onChange={(e) => setDraft({ ...draft, status: e.target.value || undefined })}>
                      <option value="">All</option>
                      {statuses.map((s) => (
                        <option key={s} value={s}>
                          {s}
                        </option>
                      ))}
                    </select>
                  </div>
                )}
                {def.searchHint && (
                  <div className="flex-1 min-w-[180px]">
                    <label className="block text-[11px] font-semibold text-slate-600 mb-1">Search</label>
                    <input
                      className={`${inputCls} w-full`}
                      placeholder={def.searchHint}
                      maxLength={100}
                      value={draft.search ?? ''}
                      onChange={(e) => setDraft({ ...draft, search: e.target.value })}
                    />
                  </div>
                )}
                <Button type="submit" variant="primary" size="sm" leftIcon={<Search className="h-3.5 w-3.5" />}>
                  Apply
                </Button>
                <Button type="button" variant="outline" size="sm" onClick={load} leftIcon={<RefreshCw className="h-3.5 w-3.5" />}>
                  Refresh
                </Button>
              </form>
              {def.code !== 'financial-summary' && (
                <div className="mt-3 flex flex-wrap gap-x-4 gap-y-1 text-[11px] text-slate-600">
                  <span className="font-semibold">Fields:</span>
                  {def.columns.map((c) => (
                    <label key={c.key} className="inline-flex items-center gap-1">
                      <input type="checkbox" checked={fields.length === 0 || fields.includes(c.key)} onChange={() => toggleField(c.key)} />
                      {c.label}
                    </label>
                  ))}
                </div>
              )}
              {def.code === 'financial-summary' && !applied.from && !applied.to && (
                <p className="text-[11px] text-slate-500 mt-2">No dates selected: the current financial year to today is used.</p>
              )}
            </Card>
          )}

          {def && (
            <div className="flex flex-wrap items-center justify-between gap-2">
              <p className="text-xs text-slate-600">
                {loading ? 'Generating…' : summaryRows ? `${summaryRows.length} lines` : result ? `${result.total} records` : ''}
              </p>
              <div className="flex gap-2">
                <Button variant="outline" size="sm" isLoading={exporting === 'csv'} disabled={!!exporting || loading} onClick={() => doExport('csv')} leftIcon={<Download className="h-3.5 w-3.5" />}>
                  CSV
                </Button>
                <Button variant="outline" size="sm" isLoading={exporting === 'xlsx'} disabled={!!exporting || loading} onClick={() => doExport('xlsx')} leftIcon={<FileSpreadsheet className="h-3.5 w-3.5" />}>
                  Excel (.xlsx)
                </Button>
                <Button variant="outline" size="sm" isLoading={exporting === 'pdf'} disabled={!!exporting || loading} onClick={() => doExport('pdf')} leftIcon={<FileText className="h-3.5 w-3.5" />}>
                  PDF
                </Button>
              </div>
            </div>
          )}

          {error && <Card className="p-4 border border-rose-200 bg-rose-50 text-xs text-rose-800">{error}</Card>}

          {def && !error && (
            <Card className="overflow-x-auto">
              <table className="min-w-full text-xs">
                <thead className="bg-slate-50 text-slate-600">
                  <tr>
                    {columns.map((c) => (
                      <th key={c.key} className={`px-3 py-2 font-semibold whitespace-nowrap ${c.type === 'money' || c.type === 'int' ? 'text-right' : 'text-left'}`}>
                        {c.label}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {!loading && rows.length === 0 && (
                    <tr>
                      <td colSpan={columns.length} className="px-3 py-8 text-center text-slate-400">
                        No records match the selected filters.
                      </td>
                    </tr>
                  )}
                  {rows.map((r, i) => (
                    <tr key={i} className="hover:bg-slate-50">
                      {columns.map((c) => (
                        <td key={c.key} className={`px-3 py-2 ${c.type === 'money' || c.type === 'int' ? 'text-right tabular-nums' : ''}`}>
                          {displayCell(r[c.key], c.type)}
                        </td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </Card>
          )}

          {result && result.totalPages > 1 && (
            <div className="flex items-center justify-end gap-2 text-xs">
              <Button variant="outline" size="sm" disabled={page <= 1 || loading} onClick={() => setPage(page - 1)}>
                Previous
              </Button>
              <span className="text-slate-600">
                Page {result.page} of {result.totalPages}
              </span>
              <Button variant="outline" size="sm" disabled={page >= result.totalPages || loading} onClick={() => setPage(page + 1)}>
                Next
              </Button>
            </div>
          )}
        </div>
      </div>

      <Card className="p-4 border border-amber-200 bg-amber-50 text-xs text-amber-900">
        Scheduled email reports are not available yet: the scheduling rules (allowed frequencies and formats) are not confirmed and no scheduler is configured.
      </Card>
    </div>
  );
};
